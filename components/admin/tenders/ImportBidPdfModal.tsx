'use client';

import React, { useState, useRef } from 'react';
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Card, CardContent } from '@/components/ui/card';
import {
  UploadCloud,
  FileText,
  Sparkles,
  CheckCircle2,
  AlertTriangle,
  Building2,
  Users,
  DollarSign,
  Clock,
  Boxes,
  Wrench,
  ArrowRight,
  ExternalLink,
  Loader2,
  Check,
} from 'lucide-react';
import { toast } from 'sonner';

interface ImportBidPdfModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSuccess: () => void;
}

export function ImportBidPdfModal({
  isOpen,
  onClose,
  onSuccess,
}: ImportBidPdfModalProps) {
  const [file, setFile] = useState<File | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [isProcessing, setIsProcessing] = useState(false);
  const [currentStep, setCurrentStep] = useState<number>(0);
  const [result, setResult] = useState<any | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const resetState = () => {
    setFile(null);
    setIsDragging(false);
    setIsProcessing(false);
    setCurrentStep(0);
    setResult(null);
  };

  const handleClose = () => {
    if (isProcessing) return;
    resetState();
    onClose();
  };

  const handleFileDrop = (e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);
    const dropped = e.dataTransfer.files?.[0];
    if (dropped) {
      if (dropped.type.includes('pdf') || dropped.name.toLowerCase().endsWith('.pdf')) {
        setFile(dropped);
        setResult(null);
      } else {
        toast.error('Please drop a valid PDF bid document');
      }
    }
  };

  const handleFileSelect = (e: React.ChangeEvent<HTMLInputElement>) => {
    const selected = e.target.files?.[0];
    if (selected) {
      if (selected.type.includes('pdf') || selected.name.toLowerCase().endsWith('.pdf')) {
        setFile(selected);
        setResult(null);
      } else {
        toast.error('Please select a valid PDF bid document');
      }
    }
  };

  const handleProcessPdf = async () => {
    if (!file) return;
    setIsProcessing(true);
    setCurrentStep(1);

    const stepInterval = setInterval(() => {
      setCurrentStep((prev) => (prev < 4 ? prev + 1 : prev));
    }, 1200);

    try {
      const formData = new FormData();
      formData.append('file', file);

      const res = await fetch('/api/sales/tenders/parse-bid-pdf', {
        method: 'POST',
        body: formData,
      });

      clearInterval(stepInterval);
      const data = await res.json();

      if (!res.ok) {
        throw new Error(data.error || 'Failed to parse bid PDF');
      }

      setResult(data);
      toast.success(
        `Successfully imported bid for ${data.parsed_data?.company_name || 'commercial client'}`
      );
    } catch (err: any) {
      clearInterval(stepInterval);
      toast.error(err.message || 'Error processing bid document');
    } finally {
      setIsProcessing(false);
    }
  };

  const labor = result?.labor_reconciliation;
  const supplies = result?.supply_reconciliation || [];
  const parsed = result?.parsed_data;
  const matchedCo = result?.matched_company;

  return (
    <Dialog open={isOpen} onOpenChange={handleClose}>
      <DialogContent className="max-w-2xl max-h-[90vh] overflow-y-auto">
        <DialogHeader>
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-indigo-500/15 border border-indigo-500/30 flex items-center justify-center text-indigo-400">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <DialogTitle className="text-base sm:text-lg font-bold">
                Import Claude Bid Proposal PDF
              </DialogTitle>
              <DialogDescription className="text-xs">
                Upload the finalized commercial bid PDF generated by Claude. Sea of Blue will auto-link company records, calculate cleaner wages, and verify supply kits.
              </DialogDescription>
            </div>
          </div>
        </DialogHeader>

        {!result ? (
          <div className="space-y-4 pt-2">
            {/* Drag and Drop Zone */}
            <div
              onDragOver={(e) => {
                e.preventDefault();
                setIsDragging(true);
              }}
              onDragLeave={() => setIsDragging(false)}
              onDrop={handleFileDrop}
              onClick={() => fileInputRef.current?.click()}
              className={`border-2 border-dashed rounded-2xl p-6 sm:p-8 text-center cursor-pointer transition-all duration-150 ${
                isDragging
                  ? 'border-indigo-500 bg-indigo-500/10'
                  : file
                  ? 'border-emerald-500/50 bg-emerald-500/5'
                  : 'border-border/80 hover:border-indigo-500/60 hover:bg-muted/30'
              }`}
            >
              <input
                ref={fileInputRef}
                type="file"
                accept=".pdf,application/pdf"
                className="hidden"
                onChange={handleFileSelect}
              />

              <div className="flex flex-col items-center justify-center space-y-2">
                <div
                  className={`w-12 h-12 rounded-2xl flex items-center justify-center mb-1 ${
                    file
                      ? 'bg-emerald-500/15 text-emerald-400 border border-emerald-500/30'
                      : 'bg-indigo-500/15 text-indigo-400 border border-indigo-500/30'
                  }`}
                >
                  {file ? <FileText className="w-6 h-6" /> : <UploadCloud className="w-6 h-6" />}
                </div>

                {file ? (
                  <div className="space-y-1">
                    <p className="text-sm font-bold text-foreground">{file.name}</p>
                    <p className="text-xs text-muted-foreground">
                      {(file.size / 1024 / 1024).toFixed(2)} MB • Ready to auto-link &amp; calculate
                    </p>
                  </div>
                ) : (
                  <div className="space-y-1">
                    <p className="text-sm font-semibold text-foreground">
                      Drop Claude Bid Proposal PDF here or click to browse
                    </p>
                    <p className="text-xs text-muted-foreground">
                      Supports commercial cleaning proposals, SOWs, and finalized bid packages
                    </p>
                  </div>
                )}
              </div>
            </div>

            {/* Live Progress Checklist during processing */}
            {isProcessing && (
              <div className="p-4 rounded-xl bg-card border border-border/80 space-y-2.5 animate-in fade-in duration-200">
                <div className="flex items-center gap-2 text-xs font-bold text-indigo-400">
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  <span>Processing Bid with Claude &amp; Matching Records...</span>
                </div>

                <div className="space-y-1.5 text-xs">
                  <div
                    className={`flex items-center gap-2 ${
                      currentStep >= 1 ? 'text-foreground' : 'text-muted-foreground'
                    }`}
                  >
                    {currentStep > 1 ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <span className="w-3.5 h-3.5 rounded-full border border-current flex items-center justify-center text-[9px]">
                        1
                      </span>
                    )}
                    <span>Uploading proposal PDF to secure vault...</span>
                  </div>

                  <div
                    className={`flex items-center gap-2 ${
                      currentStep >= 2 ? 'text-foreground' : 'text-muted-foreground'
                    }`}
                  >
                    {currentStep > 2 ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <span className="w-3.5 h-3.5 rounded-full border border-current flex items-center justify-center text-[9px]">
                        2
                      </span>
                    )}
                    <span>Reading scope, bid price &amp; milestones with Claude Sonnet...</span>
                  </div>

                  <div
                    className={`flex items-center gap-2 ${
                      currentStep >= 3 ? 'text-foreground' : 'text-muted-foreground'
                    }`}
                  >
                    {currentStep > 3 ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <span className="w-3.5 h-3.5 rounded-full border border-current flex items-center justify-center text-[9px]">
                        3
                      </span>
                    )}
                    <span>Cross-referencing General Contractor &amp; Estimator directory...</span>
                  </div>

                  <div
                    className={`flex items-center gap-2 ${
                      currentStep >= 4 ? 'text-foreground' : 'text-muted-foreground'
                    }`}
                  >
                    {currentStep >= 4 ? (
                      <Check className="w-3.5 h-3.5 text-emerald-400" />
                    ) : (
                      <span className="w-3.5 h-3.5 rounded-full border border-current flex items-center justify-center text-[9px]">
                        4
                      </span>
                    )}
                    <span>Calculating real cleaner wages and checking supply inventory...</span>
                  </div>
                </div>
              </div>
            )}

            {/* Modal Actions */}
            <div className="flex items-center justify-between pt-2 border-t border-border/60">
              <span className="text-[11px] text-muted-foreground">
                Zero manual data entry • Costs ~2 cents of API tokens
              </span>
              <div className="flex items-center gap-2">
                <Button
                  type="button"
                  variant="ghost"
                  size="sm"
                  onClick={handleClose}
                  disabled={isProcessing}
                  className="text-xs"
                >
                  Cancel
                </Button>
                <Button
                  type="button"
                  size="sm"
                  disabled={!file || isProcessing}
                  onClick={handleProcessPdf}
                  className="bg-indigo-600 hover:bg-indigo-500 text-white font-bold text-xs gap-1.5"
                >
                  {isProcessing ? (
                    <>
                      <Loader2 className="w-3.5 h-3.5 animate-spin" />
                      Analyzing Bid...
                    </>
                  ) : (
                    <>
                      <Sparkles className="w-3.5 h-3.5" />
                      Process &amp; Auto-Link Bid
                    </>
                  )}
                </Button>
              </div>
            </div>
          </div>
        ) : (
          /* SUCCESS REVIEW CARD */
          <div className="space-y-4 pt-2 text-xs animate-in fade-in duration-200">
            {/* Matched Company Banner */}
            <div className="p-3.5 rounded-xl bg-emerald-500/10 border border-emerald-500/30 flex items-start justify-between gap-3">
              <div className="flex items-center gap-2.5">
                <div className="w-9 h-9 rounded-lg bg-emerald-500/20 text-emerald-400 flex items-center justify-center shrink-0">
                  <CheckCircle2 className="w-5 h-5" />
                </div>
                <div>
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="font-extrabold text-sm text-foreground">
                      {matchedCo?.company_name}
                    </span>
                    <Badge
                      variant="outline"
                      className="bg-emerald-500/15 text-emerald-300 border-emerald-500/30 text-[10px]"
                    >
                      {matchedCo?.is_existing ? 'Existing Vendor Account Linked' : 'Added to Vendor Directory'}
                    </Badge>
                  </div>
                  <p className="text-muted-foreground text-[11px] mt-0.5">
                    Estimator: <strong className="text-foreground">{parsed?.customer_name}</strong>
                    {parsed?.customer_email ? ` (${parsed.customer_email})` : ''}
                    {parsed?.contact_title ? ` · ${parsed.contact_title}` : ''}
                  </p>
                </div>
              </div>

              {result.pdf_url && (
                <a
                  href={result.pdf_url}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-flex items-center gap-1 text-xs font-semibold text-indigo-400 hover:text-indigo-300 shrink-0"
                >
                  <span>View PDF</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              )}
            </div>

            {/* Bid Proposal Summary Grid */}
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5">
              <Card className="bg-card/70 border-border/70">
                <CardContent className="p-3 space-y-0.5">
                  <span className="text-[10px] text-muted-foreground uppercase font-bold tracking-wider">
                    Bid Amount
                  </span>
                  <p className="text-base sm:text-lg font-black text-emerald-400">
                    ${Number(parsed?.quoted_price || 0).toLocaleString()}
                  </p>
                </CardContent>
              </Card>

              <Card className="bg-card/70 border-border/70">
                <CardContent className="p-3 space-y-0.5">
                  <span className="text-[10px] text-muted-foreground uppercase font-bold tracking-wider">
                    Total Area
                  </span>
                  <p className="text-base sm:text-lg font-black text-foreground">
                    {parsed?.sqft ? `${Number(parsed.sqft).toLocaleString()} sqft` : 'Full Scope'}
                  </p>
                </CardContent>
              </Card>

              <Card className="bg-card/70 border-border/70">
                <CardContent className="p-3 space-y-0.5">
                  <span className="text-[10px] text-muted-foreground uppercase font-bold tracking-wider">
                    Labor Hours
                  </span>
                  <p className="text-base sm:text-lg font-black text-cyan-400">
                    {labor?.estimated_hours ? `${labor.estimated_hours} hrs` : '—'}
                  </p>
                </CardContent>
              </Card>

              <Card className="bg-card/70 border-border/70">
                <CardContent className="p-3 space-y-0.5">
                  <span className="text-[10px] text-muted-foreground uppercase font-bold tracking-wider">
                    Gross Margin
                  </span>
                  <p className="text-base sm:text-lg font-black text-indigo-400">
                    {labor?.gross_margin_percentage ? `${labor.gross_margin_percentage}%` : '—'}
                  </p>
                </CardContent>
              </Card>
            </div>

            {/* Project & Scope Details */}
            <div className="p-3.5 rounded-xl bg-card border border-border/80 space-y-2">
              <div className="flex items-center justify-between">
                <span className="font-bold text-foreground text-sm">{parsed?.project_name}</span>
                <span className="text-xs text-muted-foreground">{parsed?.city}</span>
              </div>

              {parsed?.scope_summary && (
                <p className="text-muted-foreground leading-relaxed text-xs">
                  {parsed.scope_summary}
                </p>
              )}

              {parsed?.phases && parsed.phases.length > 0 && (
                <div className="flex items-center gap-1.5 flex-wrap pt-1">
                  <span className="text-[10px] font-bold uppercase text-muted-foreground mr-1">
                    Phases:
                  </span>
                  {parsed.phases.map((ph: string, i: number) => (
                    <Badge key={i} variant="outline" className="text-[10px]">
                      {ph}
                    </Badge>
                  ))}
                </div>
              )}
            </div>

            {/* Cleaner Wage Reconciliation Card */}
            {labor && (
              <div className="p-3.5 rounded-xl bg-cyan-950/20 border border-cyan-500/30 space-y-2">
                <div className="flex items-center justify-between">
                  <span className="font-bold text-cyan-300 flex items-center gap-1.5 uppercase tracking-wider text-[11px]">
                    <Users className="w-3.5 h-3.5" />
                    Cleaner Wage &amp; Crew Reconciliation
                  </span>
                  <span className="text-[11px] text-muted-foreground">
                    Based on {labor.active_cleaner_pool} active cleaners in database
                  </span>
                </div>

                <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 pt-1 text-xs">
                  <div>
                    <span className="text-muted-foreground text-[10px] block">Avg Cleaner Wage:</span>
                    <strong className="text-foreground">${labor.avg_cleaner_wage?.toFixed(2)}/hr</strong>
                  </div>
                  <div>
                    <span className="text-muted-foreground text-[10px] block">Direct Payroll Cost:</span>
                    <strong className="text-foreground">${labor.total_labor_cost?.toLocaleString()}</strong>
                  </div>
                  <div>
                    <span className="text-muted-foreground text-[10px] block">Est. Crew Size:</span>
                    <strong className="text-foreground">
                      {labor.recommended_crew_size} cleaners ({labor.estimated_shifts} shifts)
                    </strong>
                  </div>
                  <div>
                    <span className="text-muted-foreground text-[10px] block">Projected Profit:</span>
                    <strong className="text-emerald-400">
                      ${labor.projected_gross_profit?.toLocaleString()}
                    </strong>
                  </div>
                </div>
              </div>
            )}

            {/* Supply OS Checklist Card */}
            {supplies.length > 0 && (
              <div className="p-3.5 rounded-xl bg-card border border-border/80 space-y-2">
                <span className="font-bold text-foreground flex items-center gap-1.5 uppercase tracking-wider text-[11px]">
                  <Boxes className="w-3.5 h-3.5 text-indigo-400" />
                  Supply OS Inventory Check ({supplies.length} required items)
                </span>

                <div className="space-y-1.5 pt-1">
                  {supplies.map((item: any, i: number) => (
                    <div
                      key={i}
                      className="flex items-center justify-between p-2 rounded-lg bg-background/60 border border-border/60 text-xs"
                    >
                      <div className="flex items-center gap-2">
                        <span className="font-semibold text-foreground">{item.item_name}</span>
                        <span className="text-muted-foreground text-[11px]">
                          ({item.quantity_needed} {item.unit})
                        </span>
                      </div>
                      <div className="flex items-center gap-2">
                        {item.in_stock ? (
                          <Badge
                            variant="outline"
                            className="bg-emerald-500/15 text-emerald-300 border-emerald-500/30 text-[10px]"
                          >
                            In Stock ({item.quantity_on_hand} on hand)
                          </Badge>
                        ) : (
                          <Badge
                            variant="outline"
                            className="bg-amber-500/15 text-amber-300 border-amber-500/30 text-[10px]"
                          >
                            Restock Alert ({item.quantity_on_hand} on hand)
                          </Badge>
                        )}
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Specialty Equipment Needed */}
            {parsed?.equipment_needed && parsed.equipment_needed.length > 0 && (
              <div className="flex items-center gap-2 flex-wrap text-xs text-muted-foreground p-2 rounded-lg bg-muted/30">
                <Wrench className="w-3.5 h-3.5 text-amber-400 shrink-0" />
                <span className="font-bold text-foreground">Equipment Required:</span>
                <span>{parsed.equipment_needed.join(', ')}</span>
              </div>
            )}

            {/* Modal Bottom Actions */}
            <div className="flex items-center justify-end gap-2 pt-3 border-t border-border/60">
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={resetState}
                className="text-xs"
              >
                Import Another PDF
              </Button>
              <Button
                type="button"
                size="sm"
                onClick={() => {
                  onSuccess();
                  handleClose();
                }}
                className="bg-indigo-600 hover:bg-indigo-500 text-white font-bold text-xs gap-1.5"
              >
                <span>Done &amp; View in Vault</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </Button>
            </div>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}
